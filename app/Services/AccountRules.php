declare(strict_types=1);

namespace LumoraFiction\Services;

/**
 * Pure checks with no database access. Each returns a plain-language problem, or null when the
 * value is acceptable.
 */
final class AccountRules
{
    public const LOGIN_NAME_MIN = 3;

    public const LOGIN_NAME_MAX = 40;

    public const DISPLAY_NAME_MIN = 2;

    public const DISPLAY_NAME_MAX = 100;

    public const EMAIL_MAX = 191;

    public static function normalizeDisplayName(string $name): string
    {
        return trim((string) preg_replace('/\s+/u', ' ', $name));
    }

    public static function normalizeEmail(string $email): string
    {
        return mb_strtolower(trim($email), 'UTF-8');
    }

    public static function loginNameProblem(string $loginName): ?string
    {
        $length = strlen($loginName);

        if ($length < self::LOGIN_NAME_MIN || $length > self::LOGIN_NAME_MAX) {
            return sprintf('Login name must be %d to %d characters long.', self::LOGIN_NAME_MIN, self::LOGIN_NAME_MAX);
        }

        // No "@" so a login name can never be mistaken for an email address at sign-in. \z, not $,
        // because $ also matches before a trailing newline.
        if (preg_match('/^[A-Za-z0-9_.-]+\z/', $loginName) !== 1) {
            return 'Login name may only contain letters, numbers, dots, hyphens, and underscores.';
        }

        return null;
    }

    public static function displayNameProblem(string $displayName): ?string
    {
        $length = mb_strlen($displayName);

        if ($length < self::DISPLAY_NAME_MIN || $length > self::DISPLAY_NAME_MAX) {
            return sprintf('Display name must be %d to %d characters long.', self::DISPLAY_NAME_MIN, self::DISPLAY_NAME_MAX);
        }

        if (preg_match('/[\x00-\x1f\x7f\p{Cc}\p{Cf}]/u', $displayName) === 1) {
            return 'Display name contains characters that are not allowed.';
        }

        return null;
    }

    public static function emailProblem(string $email): ?string
    {
        if ($email === '' || strlen($email) > self::EMAIL_MAX || filter_var($email, FILTER_VALIDATE_EMAIL) === false) {
            return 'Enter a valid email address.';
        }

        return null;
    }

    /**
     * The login name is private and the display name is public, so the account must not use the same
     * text for both: knowing a writer's public name must never reveal how to sign in as them. The
     * slug is generated by the application and is kept different from the login name there.
     */
    public static function distinctnessProblem(string $loginName, string $displayName): ?string
    {
        if (mb_strtolower($loginName, 'UTF-8') === mb_strtolower($displayName, 'UTF-8')) {
            return 'Login name must be different from your display name.';
        }

        return null;
    }
}
